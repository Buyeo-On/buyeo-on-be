회원 데이터베이스, 사진 저장소와 DB 자동 백업은 AWS 대한민국 서울 리전(ap-northeast-2)을 사용합니다. DB 자동 백업은 생성일부터 최대 7일 보관합니다. S3 사진 저장소는 버전 관리와 다른 리전 복제를 사용하지 않습니다.

운영 API 도메인은 Cloudflare Free 플랜의 프록시를 사용합니다. 지역 제한 기능을 사용하지 않아 요청은 이용자와 가까운 전 세계 Cloudflare 데이터센터에서 처리될 수 있습니다. 운영자가 설정한 사용자 지정 캐시, Logpush, 요청 본문 저장 기능은 사용하지 않습니다. Cloudflare의 기본 HTTP 처리에서 일반 요청·응답 본문은 전송 중 메모리에서 처리되며, 기본 HTTP 요청 로그 보관은 활성화하지 않습니다. 다만 보안·네트워크 운영 과정의 기술 메타데이터와 기본 캐시 대상 정적 콘텐츠는 Cloudflare의 정책과 실제 기능 설정에 따라 처리될 수 있습니다.

운영자는 수탁자에 대한 목적 외 처리 금지, 보호조치, 재위탁 관리, 권리행사 협조와 계약 종료 후 파기 등을 관리·감독하고, 업무 담당자의 접근권한을 필요한 범위로 제한합니다.

## 5. 개인정보의 국외 이전

회원 DB와 사진은 AWS 서울 리전에 보관하지만, Cloudflare 프록시를 통한 API 이용 및 이용자가 선택한 Apple 로그인·푸시 기능에는 아래와 같은 국외 처리가 발생할 수 있습니다. Cloudflare 프록시와 Apple 로그인 처리는 회원 서비스 제공 및 이용자가 선택한 로그인 방식의 계약 체결·이행에 필요한 처리로서 이 처리방침에 공개합니다. 푸시 관련 국외 이전은 이용자의 별도 선택 동의를 근거로 합니다.

