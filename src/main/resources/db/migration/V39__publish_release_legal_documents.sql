부여ON(대표 정진형, 이하 “운영자”)은 이용자의 개인정보를 중요하게 생각하며 관계 법령에 따라 다음과 같이 처리합니다. 이 처리방침은 개인정보 처리 사실을 알리는 문서이며, 위치·사진·푸시 등 선택 기능은 해당 기능을 사용할 때 별도로 안내하고 동의를 받습니다.

## 1. 개인정보의 처리 목적·항목·근거·기간

보유기간이 끝나거나 처리 목적이 달성되면 법령상 별도 보존 근거가 있는 최소 자료를 제외하고 지체 없이 파기합니다.

