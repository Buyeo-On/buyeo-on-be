사진 파일에 포함된 불필요한 GPS·기기 식별 메타데이터는 서버 전송 전에 제거합니다. 미션에 제출되지 않은 임시 사진은 객체 생성일부터 최대 24시간 이내 파기합니다. 사진 내용 자체에 다른 사람의 얼굴·차량번호·문서 등 개인정보가 포함되지 않도록 주의해 주세요.

운영자는 소셜 인증에 필요한 식별·인증정보만 처리하며 소셜 계정 비밀번호를 수집하지 않습니다. 카카오·Apple이 보유한 실명·전화번호·생년월일·성별·이메일을 부여ON 회원 프로필로 별도 저장하지 않습니다. 다만 Apple이 최초 인증 시 이용자의 선택에 따라 제공한 이름·이메일은 인증 과정에서 일시 처리될 수 있습니다.

로그인 유지 등을 위해 기기에는 인증정보, 표시 설정, 온보딩 완료 여부 등이 저장될 수 있습니다. 재방문 안내에는 회원의 기존 여행 기록에서 확인한 최근 방문 시각을 이용합니다. 광고·행동분석 SDK는 사용하지 않으며, 도입하는 경우 실제 처리 항목과 근거를 적용 전에 공개합니다.

## 2. 개인정보의 수집 방법

카카오·Apple 인증, 이용자의 직접 입력·선택·사진 제출, 단말기 권한을 통한 위치 확인, 서비스 이용 중 자동 생성되는 기록 및 고객 문의를 통해 수집합니다. 카메라 권한은 사진 미션 촬영에만 사용하며 기기의 전체 사진을 임의 수집하지 않습니다.

## 3. 개인정보의 제3자 제공과 공개 범위

1. 운영자는 법령상 근거가 있거나 이용자가 별도로 동의한 경우를 제외하고 개인정보를 제3자에게 제공하지 않습니다.
2. 현재 굿뜨래페이·부여군·상점에 회원의 개인별 계정정보·위치·방문기록·사진을 제공하지 않습니다. 실제 제휴 제공이 시작되면 제공받는 자, 목적, 항목, 기간과 거부권을 사전에 안내하고 필요한 동의를 받습니다.
3. 저장한 장소, 사진과 회고는 다른 이용자에게 자동 공개하지 않습니다. 이용자가 직접 기기 밖으로 공유한 자료는 받는 사람의 보관 범위에 들어갈 수 있습니다.

